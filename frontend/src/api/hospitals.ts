import { apiDelete, apiGet, apiPatch, apiPost } from './client'

export type HospitalType = 'hospital' | 'bloodBank'

export interface HospitalInput {
  name: string
  type: HospitalType
  address: string
  latitude: number
  longitude: number
  phone: string
  isActive: boolean
  /** Capability codes from the managed list. */
  capabilities: string[]
}

export interface Hospital extends HospitalInput {
  id: number
}

export interface Capability {
  code: string
  name: string
}

export interface Department {
  id: number
  name: string
}

export interface WardItem {
  id: number
  /** The bed board's ward id. Generated by the server, never changes. */
  code: string
  name: string
  kind: string
  departmentId: number | null
  bedCount: number
}

export interface LocationItem {
  id: number
  name: string
}

export interface HospitalDetail extends Hospital {
  departments: Department[]
  wards: WardItem[]
  locations: LocationItem[]
}

export type StructureKind = 'departments' | 'wards' | 'locations'

export const HOSPITAL_TYPES: readonly { value: HospitalType; label: string }[] = [
  { value: 'hospital', label: 'Hospital' },
  { value: 'bloodBank', label: 'Blood bank' },
]

export const typeLabel = (type: HospitalType) => HOSPITAL_TYPES.find((t) => t.value === type)?.label ?? type

export function getHospitals(): Promise<Hospital[]> {
  return apiGet<Hospital[]>('/hospitals/')
}

export function getHospital(id: number): Promise<HospitalDetail> {
  return apiGet<HospitalDetail>(`/hospitals/${id}/`)
}

export function getCapabilities(): Promise<Capability[]> {
  return apiGet<Capability[]>('/hospitals/capabilities/')
}

export function createHospital(input: HospitalInput): Promise<Hospital> {
  return apiPost<Hospital>('/hospitals/', input)
}

export function updateHospital(id: number, input: Partial<HospitalInput>): Promise<Hospital> {
  return apiPatch<Hospital>(`/hospitals/${id}/`, input)
}

/** Add a department ({name}), ward ({name, kind, departmentId}) or storage location ({name}). */
export function addStructureItem<T>(hospitalId: number, kind: StructureKind, data: Record<string, unknown>): Promise<T> {
  return apiPost<T>(`/hospitals/${hospitalId}/${kind}/`, data)
}

/** 409 {detail} when something still uses the item. */
export function removeStructureItem(hospitalId: number, kind: StructureKind, itemId: number): Promise<void> {
  return apiDelete(`/hospitals/${hospitalId}/${kind}/${itemId}/`)
}
